/**
 * ดึงชุดคำถามประจำด่านตามระดับชั้นเรียน (ป.4, ป.5, ป.6)
 */
export function getQuestionsForLevel(levelId: number, grade?: GradeLevel): Question[] {
  const levelQuestions = QUESTIONS.filter((q) => q.level === levelId);
  if (!grade) return levelQuestions;

  const matched = levelQuestions.filter(
    (q) => !q.grades || q.grades.length === 0 || q.grades.includes(grade)
  );

  return matched.length > 0 ? matched : levelQuestions;
}


